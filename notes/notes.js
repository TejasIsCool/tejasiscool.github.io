// On load
document.addEventListener("DOMContentLoaded", function() {
    const notes = document.getElementById("notes");
    for (let course in data) {
        let course_div = document.createElement("div");
        course_div.classList.add("course");


        let course_text = document.createElement("div")
        course_text.classList.add("course-text")
        course_text.innerText = "Course: " + course;
        course_div.append(course_text);
        // Replace <details> with <div> and <summary> with <div>:
        course_text.addEventListener("click", () => {
            course_div.classList.toggle("open");
        });

        let topics_wrapper = document.createElement("div");
        topics_wrapper.classList.add("topics-wrapper");
        let topics_inner = document.createElement("div");
        topics_inner.classList.add("topics-inner");



        for (let topic in data[course]) {
            let topic_div = document.createElement("div");
            topic_div.classList.add("topic");

            let topic_text = document.createElement("div");
            topic_text.classList.add("topic-text");
            topic_text.innerText = "Topic: " + topic;
            topic_div.append(topic_text);

            let content_list = document.createElement("ul")
            let content = data[course][topic]
            content.forEach(name => {
                let li = document.createElement("li");
                let link = document.createElement("a");
                link.textContent = name;
                link.href = "./notes/"+course+"/"+topic+"/"+name;
                li.append(link);
                content_list.append(li);
            })
            topic_div.append(content_list);
            topics_inner.append(topic_div);
        }
        topics_wrapper.append(topics_inner)
        course_div.append(topics_wrapper)
        notes.append(course_div);
    }
})